def _words(s):
    return set(re.findall(r"\w{4,}", s.lower()))


def search(tenant_id, query, tags, top_k=3):
    """Пошук лише в колекції свого орендаря — чужі документи недосяжні за конструкцією."""
    docs = KB.get(tenant_id, [])
    qw = _words(query)
    scored = [(2 * len(set(d["tags"]) & set(tags)) + len(qw & _words(d["text"] + d["title"])), d) for d in docs]
    return [d for s, d in sorted(scored, key=lambda x: -x[0]) if s > 0][:top_k]
